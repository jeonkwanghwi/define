/**
 * 오늘의 단어 풀 — 서버가 내려줄 단어와 그 **soft tag**.
 *
 * ── 🔴 단어를 고르는 기준 (추가·삭제할 때 반드시 읽을 것) ──
 *
 * **"ㅇㅇ(이)란 ___이다"의 빈칸이 채워지는가.** 이것 하나가 전부다.
 *
 * 아름다운 단어와 쓸 말이 떠오르는 단어는 다르다. '뭉클함'·'사무침'·'벅참'은 좋은 말이지만
 * **이미 감정의 결과**라 더 쪼갤 게 없다 — "뭉클함이란 뭉클한 것"이 되어버린다.
 * 같은 감정어라도 '불안'·'외로움'은 사유할 수 있어서 쓸 말이 나온다. 순간의 감각과 다르다.
 * '뒷모습'·'밑줄'·'손글씨'도 시적이지만 **심상이 너무 좁아** 정의할 내용이 없다.
 *
 * 그래서 걸러낸 것들:
 *   • 순간의 감각 — 뭉클함, 사무침, 벅참, 홀가분함, 초조함, 어색함…
 *   • 너무 좁은 심상 — 뒷모습, 밑줄, 손글씨, 단잠, 허기…
 *   • 추상의 추상 — 가치, 기준, 원칙, 신념(비슷하고 손에 안 잡힌다)
 *   • 서로 겹치는 말 — 지식/지혜, 배움/공부, 쉼/휴식, 버릇/습관
 *
 * 남긴 것들의 공통점: **누구나 한 입장을 가질 수 있다.** 각자 다른 답이 나오고,
 * 그 차이가 이 앱의 재미다. 사랑·돈·어른·실패처럼.
 *
 * ── 태그를 붙이는 원칙 ──
 * 2026-06-14에 "단어에 카테고리를 넣지 않는다"고 정했었다(단어는 다의적이고 분류는 자의적이라
 * "각자의 정의"라는 브랜드와 충돌한다). 그 결정이 단 조건을 그대로 지킨다:
 *   • 단일 분류가 아니라 **복수 soft tag** — 한 단어에 여러 결이 붙을 수 있다.
 *   • **시스템 단어에만** 붙인다. 사용자가 쓴 정의에는 절대 붙이지 않는다.
 *   • 태그는 **추천 가중치일 뿐** 사용자에게 보이지 않는다.
 *
 * **태그 없는 단어가 절반이 넘는다.** '시간'·'집'·'실패'는 누구의 것도 아니면서 모두의 것이다.
 * 관심사에 맞는 단어만 주면 추천이 잘 맞을수록 세계가 좁아진다 — 서비스는 7할만 관심사에서,
 * 3할은 전체에서 섞어 뽑는다.
 *
 * 태그 값은 `back/src/modules/auth/interests.ts`의 INTERESTS와 **같은 문자열**이어야 한다.
 */

